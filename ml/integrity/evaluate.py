"""How well does the detector work? Measured on synthetic platforms with planted cheaters.

Four approaches are compared, each scoring every user:
  luck only      rank users by luck_z ("who wins too much?") - the naive baseline
  rules only     the explicit rules (rules.py)
  anomaly only   the Isolation Forest percentile (model.anomaly_only)
  combined       the production scorer (model.score_users): rules + anomaly

Metrics (higher is better), each averaged over several random platforms (seeds):
  average precision  area under the precision-recall curve of the ranking: 1.0 means every
                     cheater is ranked above every honest user. Unlike accuracy it isn't fooled
                     by the imbalance (~6% cheaters: flagging nobody is 94% "accurate").
  precision@k        of the k top-ranked users (k = number of cheaters), the share who are cheaters
  flag precision     of the users actually flagged, the share who are cheaters
  flag recall        of all cheaters, the share that got flagged
  skilled flagged    honest-but-skilled users flagged by mistake (the false positive we fear most)
"""

from __future__ import annotations

import statistics

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score

from .features import user_features
from .model import FLAG_TOP_SHARE, MIN_SELECTIONS, anomaly_only, score_users
from .rules import rule_hits
from .synthetic import ABUSE_KINDS, generate


def _metrics(score: pd.Series, flagged: pd.Series, labels: pd.Series, kinds: pd.Series) -> dict:
    y = labels.loc[score.index].astype(int)
    k = int(y.sum())
    top = score.sort_values(ascending=False).index[:k]
    hit = flagged.loc[score.index]
    out = {
        "average precision": average_precision_score(y, score),
        "precision@k": float(y.loc[top].mean()),
        "flag precision": float(y[hit].mean()) if hit.any() else 0.0,
        "flag recall": float(hit[y == 1].mean()),
        "skilled flagged": int((hit & (kinds.loc[score.index] == "skilled")).sum()),
    }
    for kind in sorted(ABUSE_KINDS):
        members = kinds.loc[score.index] == kind
        out[f"recall: {kind}"] = float(hit[members].mean()) if members.any() else float("nan")
    return out


def evaluate_once(seed: int) -> dict[str, dict]:
    data = generate(seed=seed)
    features = user_features(data.bets, data.events)
    features = features[features["n_selections"] >= MIN_SELECTIONS]
    labels = data.is_abuser.reindex(features.index)
    kinds = pd.Series(data.labels).reindex(features.index)

    luck = features["luck_z"].rank(pct=True)
    rules = rule_hits(features)
    rule_score = pd.Series({u: float(u in rules) for u in features.index})
    anomaly = anomaly_only(features, seed=seed)
    combined = score_users(features, seed=seed).scores

    return {
        "luck only": _metrics(luck, luck >= 1 - FLAG_TOP_SHARE, labels, kinds),
        "rules only": _metrics(rule_score + 1e-6 * luck, rule_score > 0, labels, kinds),
        "anomaly only": _metrics(anomaly, anomaly >= 1 - FLAG_TOP_SHARE, labels, kinds),
        "combined": _metrics(combined["score"], combined["flagged"].astype(bool), labels, kinds),
    }


def evaluate(seeds=(1, 2, 3, 4, 5)) -> pd.DataFrame:
    runs = [evaluate_once(s) for s in seeds]
    table = {}
    for method in runs[0]:
        table[method] = {}
        for metric in runs[0][method]:
            values = [r[method][metric] for r in runs if not np.isnan(r[method][metric])]
            mean = statistics.fmean(values)
            sd = statistics.pstdev(values) if len(values) > 1 else 0.0
            table[method][metric] = f"{mean:.2f} ± {sd:.2f}" if metric != "skilled flagged" else f"{mean:.1f}"
    return pd.DataFrame(table)


def report(seeds=(1, 2, 3, 4, 5)) -> str:
    table = evaluate(seeds)
    data = generate(seed=seeds[0])
    counts = pd.Series(data.labels).value_counts()
    lines = [
        "# Integrity detector — evaluation on synthetic data",
        "",
        f"Generated by `python -m integrity evaluate` over {len(seeds)} simulated platforms (seeds {', '.join(map(str, seeds))}).",
        f"Each platform: {len(data.bets):,} bets from {int(counts.sum())} users — " + ", ".join(f"{n} {k}" for k, n in counts.items()) + ".",
        "Values are mean ± standard deviation across the platforms.",
        "",
        table.to_markdown(),
        "",
        "Caveat: the cheaters are simulated, so these numbers show the detector finds the patterns it",
        "was designed for. Real abuse will include patterns nobody simulated; that is what the",
        "unsupervised anomaly score is for, and why flags go to a human, not to an automatic ban.",
    ]
    return "\n".join(lines) + "\n"
