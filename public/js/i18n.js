function t(key) {
  const lang = localStorage.getItem("betzone_lang") || DEFAULT_LANG;
  return I18N[lang]?.[key] || I18N["en"][key] || key;
}

function setLang(lang) {
  localStorage.setItem("betzone_lang", lang);
  location.reload();
}

function getCurrentLang() {
  return localStorage.getItem("betzone_lang") || DEFAULT_LANG;
}

